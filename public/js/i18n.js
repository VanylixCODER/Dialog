function detectLang() {
  const saved = localStorage.getItem("dialog_lang");
  if (saved) return saved;
  const ru = ["RU", "AM", "BY", "KZ", "KG", "MD", "UA", "GE", "AZ", "UZ", "TJ", "TM"];
  try {
    const xhr = new XMLHttpRequest();
    xhr.open("GET", "https://ip-api.com/json/?fields=countryCode", false);
    xhr.send();
    if (xhr.status === 200) {
      const data = JSON.parse(xhr.responseText);
      if (ru.includes(data.countryCode)) return "ru";
    }
  } catch {}
  return "en";
}
let lang = detectLang();
function t(key, vars) { let s = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key; if (vars) for (const k in vars) s = s.replaceAll("{" + k + "}", vars[k]); return s; }
function applyI18n(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    // .call-btn elements show their label via the CSS [data-tip]::before tooltip,
    // so we must NOT also set a native `title` or the same text renders twice on hover.
    if (el.classList.contains("call-btn")) { el.removeAttribute("title"); return; }
    el.title = t(el.dataset.i18nTitle);
  });
  document.documentElement.lang = lang;
}
function setLang(l) { lang = l; localStorage.setItem("dialog_lang", l); applyI18n(); window.dispatchEvent(new Event("langchange")); }
